// Bake terrain-safe tail poses for the approved opening. No calibration work runs in the visitor's browser.
// node tools/bake-opening-clearance.mjs [http://localhost:5173]
import { chromium } from 'playwright-core';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const origin = process.argv[2] ?? 'http://localhost:5173';
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  headless: true, args: ['--use-angle=d3d11'] });
const count = 201, margin = 0.03, cap = 1.15;
const lift = new Array(count).fill(0), body = new Array(count).fill(0), support = new Array(count).fill(0), issues = [];
try {
  for (const variant of ['web', 'lite']) {
    const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
    await page.goto(`${origin}/opening-lab.html?m=${variant}&msaa=0&wind=1`, { waitUntil: 'load' });
    await page.waitForFunction(() => window.__op?.ready, null, { timeout: 120000 });
    await page.evaluate(() => { window.requestAnimationFrame = () => 0; });
    await page.waitForTimeout(100);
    for (let first = 0; first < count; first += 10) {
      const rows = await page.evaluate(({ first, count, margin, cap }) => {
        const out = [];
        for (let i = first; i < Math.min(count, first + 10); i++) {
          const progress = i / (count - 1), times = [0, 1.5, 3, 4.5, 6, 8];
          const probe = (tailLift, bodyLift = 0) => Math.min(...times.map((time) =>
            window.__op.probe({ progress, time, tailLift, bodyLift }).tailGap));
          const ground = window.__op.timeline.at(progress).ground;
          const required = ground > 0.999 ? 0.015 : margin;
          let needed = 0, bodyLift = 0, gap = probe(0);
          if (gap < required) {
            const atCap = probe(cap);
            if (atCap < required) {
              needed = cap;
              // During release/approach the bird can rise; fully planted toes stay anchored to the rock.
              if (ground < 0.999) bodyLift = required - atCap;
              else out.push({ issue: true, progress, gap: atCap, ground });
            } else {
              let lo = 0, hi = cap;
              for (let j = 0; j < 8; j++) { const mid = (lo + hi) / 2; if (probe(mid) < required) lo = mid; else hi = mid; }
              needed = hi;
            }
          }
          out.push({ i, lift: needed, body: bodyLift, ground });
        }
        return out;
      }, { first, count, margin, cap });
      for (const row of rows) {
        if (row.issue) issues.push({ variant, ...row });
        else { lift[row.i] = Math.max(lift[row.i], row.lift); body[row.i] = Math.max(body[row.i], row.body); support[row.i] = row.ground; }
      }
      console.log(variant, `${Math.min(count, first + 10)}/${count}`);
    }
    await page.close();
  }
  // Dilate the upper envelope before a light blur so corrections anticipate obstacles without sharp pose changes.
  const smooth = (raw) => {
    const envelope = raw.map((_, i) => Math.max(...Array.from({ length: 7 }, (_, k) => raw[Math.min(count - 1, Math.max(0, i + k - 3))])));
    return raw.map((minimum, i) => Math.max(minimum, Array.from({ length: 5 }, (_, k) => {
      const weight = 3 - Math.abs(k - 2);
      return weight * envelope[Math.min(count - 1, Math.max(0, i + k - 2))];
    }).reduce((a, b) => a + b, 0) / 9));
  };
  const tail = smooth(lift).map((v) => +v.toFixed(6));
  // Do not spread a flying body's correction into a planted frame.
  const airborne = smooth(body).map((v, i) => support[i] < 0.999 ? +v.toFixed(6) : 0);
  if (issues.length) {
    console.error(JSON.stringify({ message: 'Grounded tail clearance needs correction before baking', issues }, null, 2));
    process.exitCode = 1;
  } else {
    const output = fileURLToPath(new URL('../site/src/beasts/opening-clearance-data.js', import.meta.url));
    await writeFile(output, '// Generated by tools/bake-opening-clearance.mjs; both LODs, 6 wind phases.\n' +
      `export const TAIL_LIFT = ${JSON.stringify(tail)};\nexport const BODY_LIFT = ${JSON.stringify(airborne)};\n`);
    console.log(JSON.stringify({ samples: count, maxTailLift: Math.max(...tail), maxBodyLift: Math.max(...airborne), output }));
  }
} finally { await browser.close(); }
